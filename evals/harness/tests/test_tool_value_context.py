"""Tests for the C1-ctx context transform (design §4.1, finding 7).

The fixture text below is a literal copy of
`generateProjectContext()`'s output, read directly from
/Users/AlexUA_1/claude/localwp-agent-tools/src/helpers/project-context.ts
at branch `eval/headless-harness`, commit `7edd2e9`, for siteName="acme".
If the fork changes that function, this fixture goes stale — the runner's
real path calls the fork's own `--print-context` (see
# SEAM(headless-entrypoint) in strip_tool_references.py) so staleness here
only affects this test's realism, never the harness's actual output.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

MODULE_PATH = (
    Path(__file__).resolve().parents[3]
    / "evals" / "suites" / "localwp-agent-tools-value" / "stack" / "strip_tool_references.py"
)
_spec = importlib.util.spec_from_file_location("strip_tool_references", MODULE_PATH)
strip_tool_references_module = importlib.util.module_from_spec(_spec)
assert _spec.loader is not None
_spec.loader.exec_module(strip_tool_references_module)
strip_tool_references = strip_tool_references_module.strip_tool_references

REAL_FORK_CONTEXT = """# WordPress Site: acme

This is a WordPress site managed by [Local](https://localwp.com/). It has a Local MCP server configured that provides tools for interacting with the site.

Use the `get_site_info` tool to get environment details (PHP/MySQL versions, paths, active plugins, theme, etc.).

## File Structure (relative to site root)
- WordPress root: app/public/
- Theme files: app/public/wp-content/themes/
- Plugin files: app/public/wp-content/plugins/
- Uploads: app/public/wp-content/uploads/
- Logs: logs/
- Local config: conf/

## Notes
- For database operations, prefer WP-CLI commands via the `wp_cli` tool (e.g. `wp db query`, `wp db export`, `wp search-replace`).
- This file was auto-generated by the Agent Tools add-on for Local.
"""

EXPECTED_STRIPPED = """# WordPress Site: acme

## File Structure (relative to site root)
- WordPress root: app/public/
- Theme files: app/public/wp-content/themes/
- Plugin files: app/public/wp-content/plugins/
- Uploads: app/public/wp-content/uploads/
- Logs: logs/
- Local config: conf/

## Notes
- This file was auto-generated by the Agent Tools add-on for Local.
"""


def test_strip_tool_references_against_the_real_fork_text():
    assert strip_tool_references(REAL_FORK_CONTEXT) == EXPECTED_STRIPPED


def test_no_mcp_tool_wp_cli_or_get_site_info_survives():
    stripped = strip_tool_references(REAL_FORK_CONTEXT)
    for token in ("MCP", "wp_cli", "get_site_info"):
        assert token not in stripped
    # Lowercase "tool" specifically (not "Tools", the product name in the
    # retained auto-generated notice — see the module docstring).
    assert "tool" not in stripped


def test_title_and_file_structure_and_notice_survive():
    stripped = strip_tool_references(REAL_FORK_CONTEXT)
    assert "# WordPress Site: acme" in stripped
    assert "## File Structure (relative to site root)" in stripped
    assert "- WordPress root: app/public/" in stripped
    assert "auto-generated by the Agent Tools add-on for Local" in stripped


def test_known_discrepancy_the_managed_by_local_sentence_is_also_dropped():
    """Documents the design/implementation mismatch described in the module
    docstring: design §4.1's prose says this sentence survives, but it
    shares one physical line with the MCP/tools clause in the real fork
    text, so the literal line-drop rule removes it too."""
    stripped = strip_tool_references(REAL_FORK_CONTEXT)
    assert "managed by" not in stripped
    assert "localwp.com" not in stripped


def test_idempotent_on_already_stripped_text():
    once = strip_tool_references(REAL_FORK_CONTEXT)
    twice = strip_tool_references(once)
    assert once == twice


def test_blank_run_collapse_on_synthetic_input():
    text = "keep 1\ntool line\n\nkeep 2\nkeep 3\n"
    stripped = strip_tool_references(text)
    assert stripped == "keep 1\n\nkeep 2\nkeep 3\n"


def test_mcp_token_match_is_case_sensitive_uppercase_only():
    # A lowercase "mcp" substring must NOT trigger a drop (case-sensitive),
    # but the literal uppercase token "MCP" must.
    text = "keep: mcpserver lowercase\ndrop: real MCP mention\nkeep 2\n"
    stripped = strip_tool_references(text)
    assert stripped == "keep: mcpserver lowercase\nkeep 2\n"


def test_no_trailing_newline_preserved():
    text = "keep\ntool drop"
    assert strip_tool_references(text) == "keep"
