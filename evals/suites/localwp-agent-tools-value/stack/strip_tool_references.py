#!/usr/bin/env python3
"""stripToolReferences — the deterministic transform for the C1-ctx arm.

Design: docs/wordpress/localwp-agent-tools-eval-design-2026-09-02.md §4.1
(finding 7): "The tool-stripped context is stripToolReferences(
generateProjectContext(name)): drop every line containing MCP, tool,
`wp_cli` or `get_site_info`, then collapse blank runs."

`generateProjectContext` now lives, Local-free, at
/Users/AlexUA_1/claude/localwp-agent-tools/src/helpers/project-context.ts
(branch eval/headless-harness, commit 7edd2e9) and is printed verbatim by
the fork's headless entrypoint: `agent-tools-headless --print-context
<siteName>`. Fetching that text is the harness's job at run time —
# SEAM(headless-entrypoint): the runner invokes that subprocess and pipes
its stdout through `strip_tool_references()`. This module only implements
the pure transform, so it is testable with no Node process at all (see
evals/harness/tests/test_tool_value_context.py).

Known discrepancy against the design's own worked example (recorded here,
not silently resolved — see the test file for the concrete before/after):
the design's prose says the stripped residue keeps "the title, [...] 'This
is a WordPress site managed by [Local](https://localwp.com/).' sentence,
the whole File Structure section, and the auto-generated notice." Read
literally, "drop every line containing MCP [or] tool" operates on physical
lines. In the real generateProjectContext() output, the "managed by Local"
sentence and the "It has a Local MCP server ... provides tools ..." sentence
sit on the *same* physical line, joined by ". ". A literal line-level drop
therefore removes the "managed by Local" sentence too, because the line it
shares also contains "MCP" and "tools". The design's expected-residue prose
assumes a document shape (one sentence per line) that the real fork text
does not have. This implementation follows the literal, stated rule
(line-level, not sentence-level) rather than inventing a sentence-splitting
step the design never specifies; the mismatch against the design's prose
example is flagged for the design author to reconcile — either by amending
generateProjectContext to put "managed by Local" on its own line, or by
amending the transform to operate per-sentence.
"""
from __future__ import annotations

import sys

# Case-sensitive substrings. "MCP" and lowercase "tool" (which also catches
# "tools") are matched as plain substrings, not word-bounded, because the
# design names them as bare tokens, not code-span identifiers. `wp_cli` and
# `` `get_site_info` `` are the two tool names, written in the design in
# backtick code spans; the backticks are markdown formatting the generated
# text actually contains, but matching the bare name (no backticks) is
# sufficient and more robust to formatting drift.
#
# Case sensitivity matters: the auto-generated notice line ("This file was
# auto-generated by the Agent Tools add-on for Local.") contains "Tools"
# (capitalized, the product name) but no lowercase "tool" substring. The
# design's expected residue keeps that line. Matching "tool" case-sensitively
# (lowercase only) is the only reading of the rule consistent with that
# stated residue; a case-insensitive match would also drop the notice line,
# contradicting the design's own worked example.
_DROP_SUBSTRINGS: tuple[str, ...] = ("MCP", "tool", "wp_cli", "get_site_info")


def _line_mentions_a_tool(line: str) -> bool:
    return any(token in line for token in _DROP_SUBSTRINGS)


def _collapse_blank_runs(lines: list[str]) -> list[str]:
    collapsed: list[str] = []
    previous_blank = False
    for line in lines:
        blank = line.strip() == ""
        if blank and previous_blank:
            continue
        collapsed.append(line)
        previous_blank = blank
    return collapsed


def strip_tool_references(text: str) -> str:
    """Drop every line naming a tool/MCP capability; collapse resulting blank runs."""
    has_trailing_newline = text.endswith("\n")
    lines = text.split("\n")
    if has_trailing_newline and lines and lines[-1] == "":
        lines = lines[:-1]
    kept = [line for line in lines if not _line_mentions_a_tool(line)]
    collapsed = _collapse_blank_runs(kept)
    result = "\n".join(collapsed)
    return result + "\n" if has_trailing_newline else result


def main(argv: list[str]) -> int:
    text = sys.stdin.read()
    sys.stdout.write(strip_tool_references(text))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
